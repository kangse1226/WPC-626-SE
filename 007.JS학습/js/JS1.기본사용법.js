/*************************************************
함수명: 움직여랏
기능: 위치값 이동 및 트랜지션, 동영상 태그넣기
사용태그: iframe - 동영상 불러오는(걸로 많이 쓰는) 태그 

*************************************************/
function 움직여랏(나야나, 이동값, 동영상아이디) {
  //나야나 - 이벤트발생요소 전달변수
 //이동값 - right 속성값에서 뺄 숫자값에 곱할 숫자
//  -> 1,2,3 (왼쪽에서부터 200px 400px 600px 떨어지려고)
// 동영상 아이디 - iframe에서 사용할 유튜브 동영상 id  

  //1. 함수호출 확인 및 전달변수값 확인!//////////////////////
  console.log(
    "당장움직여!!", 
    나야나,
    이동값
);
  //2. CSS속성값 변경하기///////////////////////////////////
//   -> 문자열 사이에 변수 넣기!!!!@@@-> "문자열"+변수+"문자열"

  나야나.style.right = "calc(100% - 200px * "+이동값+")";
  나야나.style.top = "calc(100% - 200px)";
  나야나.style.transition = "right 2s, top 0.5s ease-in 2s";

  //3. 내부에 html 넣기: 동영상 iframe (inline frame)///////
//   백틱 ``문자열 내부에 변수를 사용할 경우 ${변수}형식을 사용한다!!!
  나야나.innerHTML = `<iframe
    src='https://www.youtube.com/embed/${동영상아이디}?autoplay=1&mute=1' 
    allow='autoplay'></iframe>`; //백틱안에 변수쓸때는 ${} 이렇게@@@@
    //@@@@@@@@@@@@@@@@@@@@@@@@보관법이라고 한대@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@@

  //4. 내부의 아이프레임 CSS 넣기//////////////////////////
  //getElementsByTagName(태그명)
//   가져와!get 요소들을 Elements 태그이름으로 By Tag Name
//-> 태그요소도 여러개 사용하므로 순번선택필수! item(순번)
  나야나.getElementsByTagName("iframe").item(0).style.cssText = `
    position: absolute;
    border: none;
    width: 200px;
    height: 200px;
    border-radius: 50%;
    `;
} //움직여랏 함수의 끝/////////////////////////////
